        private IReadOnlyList<INamedTypeSymbol> GetAllTypes(IAssemblySymbol symbol)
        {
            var result = new List<INamedTypeSymbol>();

            GetAllTypes(result, symbol.GlobalNamespace);

            result.Sort((x, y) => x.MetadataName.CompareTo(y.MetadataName));

            return result;
        }

        private void GetAllTypes(List<INamedTypeSymbol> result, INamespaceOrTypeSymbol symbol)
        {
            if (symbol is INamedTypeSymbol type)
            {
                result.Add(type);
            }

            foreach (var child in symbol.GetMembers())
            {
                if (child is INamespaceOrTypeSymbol nsChild)
                {
                    GetAllTypes(result, nsChild);
                }
            }
        }

        /// <summary>收集类型自身及其基类声明的实例属性（基类在前，保持源码顺序）。</summary>
        private IReadOnlyList<IPropertySymbol> GetInheritedProperties(INamedTypeSymbol type, INamedTypeSymbol syntaxNodeType)
        {
            var levels = new List<List<IPropertySymbol>>();
            var current = type;

            while (current != null &&
                   !SymbolEqualityComparer.Default.Equals(current, syntaxNodeType) &&
                   current.SpecialType != SpecialType.System_Object)
            {
                levels.Add(current.GetMembers().OfType<IPropertySymbol>().Where(p => !p.IsStatic).ToList());

                current = current.BaseType;
            }

            levels.Reverse();

            return levels.SelectMany(l => l).ToList();
        }

        private bool IsDerivedFrom(ITypeSymbol type, INamedTypeSymbol baseType)
        {
            var current = type;

            while (current != null)
            {
                if (SymbolEqualityComparer.Default.Equals(current, baseType))
                {
                    return true;
                }

                current = current.BaseType;
            }

            return false;
        }

        private bool IsPartial(INamedTypeSymbol type)
        {
            foreach (var declaration in type.DeclaringSyntaxReferences)
            {
                var syntax = declaration.GetSyntax();

                if (syntax is ClassDeclarationSyntax classDeclaration)
                {
                    foreach (var modifier in classDeclaration.Modifiers)
                    {
                        if (modifier.ValueText == "partial")
                        {
                            return true;
                        }
                    }
                }
            }

            return false;
        }
